import fs from "node:fs";
import { launch, login, base, shots, ok } from "./_lib.mjs";
const { browser, page } = await launch();
const N = Date.now(); const DIGITS = "9" + String(N).slice(-9);
await login(page);
// company
await page.goto(base + "/companies");
await page.click("[data-open=company-dialog]");
await page.fill("#company-dialog #name", `Acme Patsanstha ${N}`);
await page.fill("#company-dialog #city", "Pune");
await page.fill("#company-dialog #state", "Maharashtra");
await page.fill("#company-dialog #tags", "priority, patsanstha");
await page.click("#company-dialog button[type=submit]");
await page.waitForURL("**/companies/*");
const companyUrl = page.url();
ok("company created", (await page.textContent("h1")).includes("Acme Patsanstha"));
ok("tags shown", (await page.textContent("body")).includes("patsanstha"));
// duplicate company warns
await page.goto(base + "/companies");
await page.click("[data-open=company-dialog]");
await page.fill("#company-dialog #name", `acme patsanstha ${N}`);
await page.click("#company-dialog button[type=submit]");
await page.waitForSelector("[data-testid=duplicates]");
ok("duplicate company warned", true);
ok("dialog kept open with values", (await page.inputValue("#company-dialog #name")) === `acme patsanstha ${N}`);
await page.screenshot({ path: `${shots}/05-company-duplicate.png` });
// contact with company picker
await page.goto(base + "/contacts");
await page.click("[data-open=contact-dialog]");
await page.fill("#contact-dialog #first_name", "Priya");
await page.fill("#contact-dialog #last_name", `Shah ${N}`);
await page.fill("#contact-dialog #email", `priya${N}@acme.in`);
await page.fill("#contact-dialog #phone", DIGITS.slice(0, 5) + " " + DIGITS.slice(5));
await page.fill("#contact-dialog [data-picker] input[type=text]", "Acme");
await page.waitForSelector("#contact-dialog .picker-list button");
await page.locator("#contact-dialog .picker-list button", { hasText: `Acme Patsanstha ${N}` }).click();
await page.click("#contact-dialog button[type=submit]");
await page.waitForURL("**/contacts/*");
const contactUrl = page.url();
ok("contact created and linked", (await page.textContent("body")).includes(`Acme Patsanstha ${N}`));
await page.screenshot({ path: `${shots}/06-contact.png` });
// duplicate by phone (different format) -> warn -> create anyway
await page.goto(base + "/contacts");
await page.click("[data-open=contact-dialog]");
await page.fill("#contact-dialog #first_name", "Priya");
await page.fill("#contact-dialog #last_name", "Duplicate");
await page.fill("#contact-dialog #phone", "+91-" + DIGITS);
await page.click("#contact-dialog button[type=submit]");
await page.waitForSelector("[data-testid=duplicates]");
ok("duplicate contact warned by phone", (await page.textContent("[data-testid=duplicates]")).includes("Same phone"));
await page.click("[data-testid=duplicates] button[name=force]");
await page.waitForURL("**/contacts/*");
const dupUrl = page.url();
ok("create anyway works", dupUrl !== contactUrl && dupUrl.includes("/contacts/"));
// notes + files
await page.goto(contactUrl);
await page.click("[data-tab=notes]");
await page.fill("textarea[name=body]", "Spoke on the phone, interested in SyncLMS demo.");
await page.click("form[action='/notes'] button[type=submit]");
await page.waitForSelector("[data-testid=note]");
ok("note added", (await page.textContent("[data-testid=note]")).includes("Spoke on the phone"));
await page.click("[data-tab=files]");
const tmp = "tmp/sample.txt";
fs.writeFileSync(tmp, "hello synccrm php");
await page.setInputFiles("input[type=file]", tmp);
await page.click("form[action='/attachments'] button[type=submit]");
await page.waitForSelector("[data-testid=file]");
const href = await page.getAttribute("[data-testid=file] a", "href");
const dl = await page.evaluate(async (h) => { const r = await fetch(h); return [r.status, await r.text()]; }, href);
ok("file uploaded and downloadable", dl[0] === 200 && dl[1] === "hello synccrm php");
await page.click("[data-tab=timeline]");
ok("timeline shows note and file", (await page.textContent("[data-panel=timeline]")).includes("Note by") && (await page.textContent("[data-panel=timeline]")).includes("File: sample.txt"));
await page.screenshot({ path: `${shots}/07-contact-timeline.png` });
// edit contact
await page.click("[data-open=contact-dialog]");
await page.fill("#contact-dialog #job_title", "Chairman");
await page.click("#contact-dialog button[type=submit]");
await page.waitForSelector("[data-testid=form-success]");
ok("contact edited", (await page.textContent("body")).includes("Chairman"));
// merge duplicate into original
await page.click("[data-dropdown]");
await page.click("button[data-open=merge-dialog]");
await page.fill("#merge-dialog [data-picker] input[type=text]", "Duplicate");
await page.waitForSelector("#merge-dialog .picker-list button");
await page.locator("#merge-dialog .picker-list button", { hasText: "Priya Duplicate" }).first().click();
await page.click("#merge-dialog button[type=submit]");
await page.waitForSelector("[data-testid=form-success]");
const dupResp = await page.goto(dupUrl);
ok("merged source gone (404)", dupResp.status() === 404);
// share with team (Pune Sales exists from test 01)
await page.goto(contactUrl);
await page.click("[data-dropdown]");
await page.click("button[data-open=share-dialog]");
await page.selectOption("#share-team", { label: "Pune Sales" });
await page.check("#share-dialog input[name=can_edit]");
await page.click("#share-dialog button[type=submit]");
await page.waitForSelector("[data-testid=form-success]");
ok("shared with team", (await page.textContent("body")).includes("Shared with 1"));
// list filters + export
await page.goto(base + "/contacts?q=Priya");
ok("search filter works", (await page.locator("[data-testid=contacts-table] tbody tr").count()) >= 1);
await page.goto(base + "/contacts?tag=priority");
await page.goto(base + "/companies?tag=priority");
ok("tag filter works", (await page.locator("[data-testid=companies-table] tbody tr").count()) >= 1);
await page.click("[data-open=save-view-dialog]");
await page.fill("#view-name", "Priority accounts");
await page.check("#save-view-dialog input[name=is_shared]");
await page.click("#save-view-dialog button[type=submit]");
await page.waitForSelector("[data-testid=form-success]");
ok("saved view chip", (await page.textContent("[data-testid=saved-views]")).includes("Priority accounts"));
const csv = await page.evaluate(async () => { const r = await fetch("/export/companies?tag=priority"); return [r.status, r.headers.get("content-type"), await r.text()]; });
ok("csv export", csv[0] === 200 && csv[1].includes("text/csv") && csv[2].includes("Acme Patsanstha"));
// member with team share can edit (rahul is in Pune Sales? test01 added members index 1,2 -> Sneha & Rahul)
const ctx2 = await browser.newContext(); const p2 = await ctx2.newPage();
await login(p2, "rahul@syncworkstech.com");
await p2.goto(contactUrl);
ok("team member sees edit button", (await p2.locator("[data-open=contact-dialog]").count()) === 1);
await p2.goto(companyUrl);
ok("member cannot edit unshared company owned by other", (await p2.locator("[data-open=company-dialog]").count()) === 0);
await ctx2.close();
await browser.close();
